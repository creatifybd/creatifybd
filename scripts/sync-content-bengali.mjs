async function syncToFirestore() {
  console.log('🚀 Syncing Bengali content to Firestore...');
  try {
    await setDoc(doc(db, 'settings', 'content'), bengaliContent, { merge: false });
    console.log('✅ Bengali content successfully written to Firestore!');
    console.log('   Version:', CONTENT_VERSION);
    console.log('   Hero title:', bengaliContent.hero.title);
    process.exit(0);
  } catch (err) {
    console.error('❌ Error writing to Firestore:', err.message);
    process.exit(1);
  }
}

